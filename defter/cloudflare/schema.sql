CREATE TABLE IF NOT EXISTS notes (id TEXT PRIMARY KEY, m INTEGER NOT NULL, d TEXT NOT NULL, rev INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS notes_rev ON notes (rev);
CREATE TABLE IF NOT EXISTS counter (id INTEGER PRIMARY KEY CHECK (id = 1), rev INTEGER NOT NULL);
INSERT OR IGNORE INTO counter (id, rev) VALUES (1, 0);
CREATE TABLE IF NOT EXISTS cfg (k TEXT PRIMARY KEY, v TEXT NOT NULL);
