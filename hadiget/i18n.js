let lang = 'tr';

export function detectLang(pref) {
  if (pref === 'tr' || pref === 'en') return pref;
  const n = (navigator.language || 'tr').toLowerCase();
  return n.startsWith('tr') ? 'tr' : 'en';
}

export function getLang() {
  return lang;
}

export function setLang(pref) {
  lang = detectLang(pref);
  document.documentElement.lang = lang;
  applyI18n();
}

export function t(key, params) {
  let s = D[lang][key] ?? D.tr[key] ?? key;
  if (params) for (const k in params) s = s.replaceAll('{' + k + '}', params[k]);
  return s;
}

export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((e) => (e.textContent = t(e.dataset.i18n)));
  root.querySelectorAll('[data-i18n-html]').forEach((e) => (e.innerHTML = t(e.dataset.i18nHtml)));
  root.querySelectorAll('[data-i18n-ph]').forEach((e) => e.setAttribute('placeholder', t(e.dataset.i18nPh)));
  root.querySelectorAll('[data-i18n-aria]').forEach((e) => e.setAttribute('aria-label', t(e.dataset.i18nAria)));
  root.querySelectorAll('[data-version]').forEach((e) => (e.textContent = t('ver', { v: self.APP_VERSION || '' })));
}

